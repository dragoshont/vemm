"use strict";
var assert = require("assert");
var playback = require("../../samsung/Vemm/js/playback.js");
var local = playback.adaptivePolicy({ enabled: true, quality: "original", location: "lan" });
var remote = playback.adaptivePolicy({ enabled: true, quality: "original", location: "wan" });
assert.strictEqual(local.quality(), "original");
assert.strictEqual(remote.quality(), "1080", "Remote Auto starts with an 8 Mbps ceiling, never an Original label");
var capped = playback.adaptivePolicy({ enabled: true, quality: "720l", location: "wan" });
assert.strictEqual(capped.quality(), "720l", "Auto never raises the explicit ceiling");
local.ready(0);
assert.strictEqual(local.buffer(true, 1000, true), null);
assert.strictEqual(local.buffer(false, 12000, true), null, "Startup buffering is excluded");
local.buffer(true, 31000, true);
assert.strictEqual(local.buffer(false, 40000, true), "1080h", "One long rebuffer reduces one rung");
local.ready(41000);
local.buffer(true, 72000, true);
assert.strictEqual(local.buffer(false, 82000, true), null, "Cooldown prevents repeated pipeline churn");
local.buffer(true, 105000, true);
assert.strictEqual(local.buffer(false, 114000, true), "1080", "Later rebuffering can reduce another rung");
local.ready(115000);
local.buffer(true, 180000, false);
assert.strictEqual(local.buffer(false, 190000, false), null, "Pausing must not request an autoplaying adaptation");
local.buffer(true, 200000, true);
assert.strictEqual(local.buffer(false, 202000, true), null);
local.buffer(true, 205000, true);
assert.strictEqual(local.buffer(false, 207000, true), "720", "Two genuine stalls in a minute also reduce quality");
["disabled", "force"].forEach(function (mode) {
    var fixed = playback.adaptivePolicy({ enabled: mode !== "disabled", directPlay: mode,
        quality: "original", location: "wan" });
    fixed.ready(0);
    fixed.buffer(true, 31000, true);
    assert.strictEqual(fixed.buffer(false, 90000, true), null);
    assert.strictEqual(fixed.quality(), "original", "Explicit fixed/Force playback is untouched");
});
var floor = playback.adaptivePolicy({ enabled: true, quality: "480", location: "wan" });
floor.ready(0);
floor.buffer(true, 31000, true);
assert.strictEqual(floor.buffer(false, 41000, true), null, "The ladder has a hard lower bound");
console.log("Tizen bounded opt-in adaptive quality/local-remote policy: passed");
